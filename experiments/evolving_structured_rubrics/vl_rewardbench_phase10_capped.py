def _compatible_specs(old: Mapping[str, Any], new: Mapping[str, Any]) -> bool:
    old_value = json.loads(json.dumps(old, ensure_ascii=False, allow_nan=False))
    new_value = json.loads(json.dumps(new, ensure_ascii=False, allow_nan=False))
    old_decoding = dict(old_value.pop("decoding_config"))
    new_decoding = dict(new_value.pop("decoding_config"))
    if old_value != new_value:
        return False
    if old_decoding.get("max_tokens") is not None:
        return False
    expected = dict(old_decoding)
    expected["max_tokens"] = MAX_TOKENS
    return new_decoding == expected


def _safe_pairwise_entry(
    value: Mapping[str, Any], old_spec: Mapping[str, Any]
) -> tuple[PairwiseVoteOutput | None, ModelCallMetrics | None, str | None]:
    expected_fields = {
        "cache_schema_version", "kind", "key_sha256", "key_payload",
        "output", "generation_metrics",
    }
    if not isinstance(value, dict) or set(value) != expected_fields:
        return None, None, "cache_schema_invalid"
    if value.get("kind") != "pairwise":
        return None, None, "cache_kind_invalid"
    key_payload = value.get("key_payload")
    if not isinstance(key_payload, dict):
        return None, None, "key_payload_invalid"
    if canonical_sha256(key_payload) != value.get("key_sha256"):
        return None, None, "key_sha256_invalid"
    if key_payload.get("request_spec") != old_spec:
        return None, None, "source_request_identity_mismatch"
    try:
        output = PairwiseVoteOutput.from_dict(value["output"])
        metrics = ModelCallMetrics.from_dict(value["generation_metrics"])
    except (TypeError, ValueError):
        return None, None, "cached_value_invalid"
    if not output.parse_ok or not output.answer_valid or output.attempt_count != 1:
        return None, None, "output_not_first_attempt_valid"
    if not isinstance(output.raw_response, str):
        return None, None, "raw_response_missing"
    try:
        reparsed = parse_pairwise_vote_response(output.raw_response)
    except Exception:
        return None, None, "raw_response_reparse_failed"
    if (reparsed.vote != output.vote or reparsed.answer_valid != output.answer_valid
            or reparsed.thought != output.thought):
        return None, None, "raw_response_projection_mismatch"
    if (not metrics.usage_complete or metrics.output_tokens is None
            or metrics.output_tokens >= MAX_TOKENS):
        return None, None, "cap_may_bind"
    if (metrics.api_attempts != 1 or metrics.parse_retries != 0
            or metrics.error_count != 0):
        return None, None, "generation_not_single_clean_attempt"
    return output, metrics, None


def _validate_source_contract(
    source_manifest: Mapping[str, Any], target_manifest: Mapping[str, Any]
) -> None:
    source_dataset = source_manifest.get("dataset")
    target_dataset = target_manifest.get("dataset")
    if not isinstance(source_dataset, dict) or not isinstance(target_dataset, dict):
        raise RuntimeError("capped cache source contract drift: dataset")
    # ``record_sha256`` includes each experiment's materialized image path.  The
    # path necessarily changes between the immutable v1 and isolated v2 output
    # directories, while the actual worker fingerprint hashes the image bytes.
    # Freeze the stable source identity here; copied cache keys retain the
    # content-based sample fingerprint and therefore miss safely if any model
    # input differs.
    for field in ("path", "sha256", "count"):
        if source_dataset.get(field) != target_dataset.get(field):
            raise RuntimeError(f"capped cache source contract drift: dataset.{field}")
    for field in (
        "order_schedule_sha256", "endpoint_schedule_sha256",
        "counterbalance", "native", "systems", "root_prediction_reuse",
        "endpoint_pool", "selection_after_benchmark_forbidden",
    ):
        if source_manifest.get(field) != target_manifest.get(field):
            raise RuntimeError(f"capped cache source contract drift: {field}")
    if not _compatible_specs(
        source_manifest["structured_worker_request_spec"],
        target_manifest["structured_worker_request_spec"],
    ):
        raise RuntimeError("capped and uncapped structured request specs are incompatible")


