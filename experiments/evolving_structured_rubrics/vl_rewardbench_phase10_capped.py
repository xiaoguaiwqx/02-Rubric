def native_fallback_run(config: Mapping[str, Any], output: Path) -> None:
    _require_public(STAGE_NATIVE_FALLBACK_FREEZE)
    target, _, records, _, _, _ = _load_v2_frozen(config, output)
    work = target / "native_fallback_qwen35_397b"
    manifest = load_json(work / "frozen_manifest.json")
    _validate_native_fallback_sources(target, manifest)
    if _native_fallback_profile(config) != manifest["parser_profile"]:
        raise RuntimeError("Native fallback parser profile drifted")
    api_key = os.environ.get(manifest["parser_profile"]["api_key_env"], "")
    if not api_key:
        raise RuntimeError(
            f"environment variable {manifest['parser_profile']['api_key_env']!r} "
            "is required for the 397B Native fallback parser")
    pool = AvailableSlotBackendPool(BackendPoolSpec.from_dict(
        manifest["parser_profile"]["backend_pool"]))
    native_by_replicate = {
        replicate: load_json(target / "run/native" / f"replicate_{replicate:02d}.json")
        for replicate in range(1, v1.legacy.K + 1)
    }
    callback = make_progress_callback(
        work, "native_qwen35_fallback", len(manifest["items"]), pool)

    def one(index: int, item: Mapping[str, Any]):
        replicate = int(item["replicate"])
        source = native_by_replicate[replicate][int(item["sample_index"])]
        if canonical_sha256(source["raw_response"]) != item["raw_response_sha256"]:
            raise RuntimeError(f"Native fallback raw response drift: {item['key']}")
        cache_key = canonical_sha256({
            'key': item['key'],
            'parser_profile': manifest['parser_profile'],
        })
        cache_path = work / "cache" / f"{cache_key}.json"
        if cache_path.exists():
            state = load_json(cache_path)
            metrics = combine_model_call_metrics(
                ModelCallMetrics.from_dict(value["metrics"]) for value in state["attempts"])
            return index, item, state, metrics
        attempts = []
        choice = None
        for attempt_number in range(1, NATIVE_FALLBACK_MAX_ATTEMPTS + 1):
            raw, call_metrics = pool.call(
                _native_fallback_prompt(source["raw_response"]),
                request_type="vlrb_native_text_parse_fallback",
                request_key=str(item["key"]),
                structured_attempt=attempt_number,
                agent_args={
                    "model": manifest["parser_profile"]["model"],
                    "api_keys": api_key,
                    "request_kwargs": manifest["parser_profile"]["request_kwargs"],
                    "api_retry_attempts": config["api_retry_attempts"],
                },
            )
            choice = _parse_native_fallback(raw)
            attempts.append({
                "attempt_number": attempt_number,
                "raw_response": raw,
                "choice": choice,
                "metrics": ModelCallMetrics.from_agent_calls((call_metrics,)).to_dict(),
            })
            if choice is not None:
                break
        state = {
            "schema_version": FORMAT_REPAIR_SCHEMA_VERSION,
            "key": item["key"],
            "raw_response_sha256": item["raw_response_sha256"],
            "choice": choice,
            "parse_ok": choice is not None,
            "attempts": attempts,
        }
        atomic_write_json(cache_path, state)
        metrics = combine_model_call_metrics(
            ModelCallMetrics.from_dict(value["metrics"]) for value in attempts)
        return index, item, state, metrics

    results = [None] * len(manifest["items"])
    with ThreadPoolExecutor(max_workers=pool.spec.global_request_concurrency) as executor:
        futures = {executor.submit(one, index, item): index
                   for index, item in enumerate(manifest["items"])}
        for future in as_completed(futures):
            index, item, state, metrics = future.result()
            results[index] = {**dict(item), **state}
            callback(index, str(item["sample_id"]), metrics)
    if any(value is None for value in results):
        raise RuntimeError("Native fallback result matrix is incomplete")
    atomic_write_json(work / "fallback_overlay.json", {
        "schema_version": FORMAT_REPAIR_SCHEMA_VERSION,
        "items": results,
    })
    atomic_write_json(work / "provenance.json", pool.provenance_dict())
    recovered = sum(bool(value["parse_ok"]) for value in results)
    details = {
        "target_count": len(results),
        "recovered_count": recovered,
        "unresolved_count": len(results) - recovered,
        "model_requests": sum(len(value["attempts"]) for value in results),
    }
    v1._status(target, STAGE_NATIVE_FALLBACK_RUN, details)
    print(json.dumps(details, indent=2, ensure_ascii=False))


