    atomic_write_json(work / "frozen_manifest.json", manifest)
    details = {
        "target_count": len(items),
        "max_attempts": NATIVE_RETRY_MAX_ATTEMPTS,
        "endpoint_counts": {
            endpoint_id: sum(item["source_endpoint_id"] == endpoint_id
                             for item in items)
            for endpoint_id in v1.ENDPOINT_IDS
        },
    }
    v1._status(target, STAGE_NATIVE_RETRY_FREEZE, details)
    print(json.dumps(details, indent=2, ensure_ascii=False))


