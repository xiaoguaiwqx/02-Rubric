def _capped_config(config: Mapping[str, Any]) -> dict[str, Any]:
    value = json.loads(json.dumps(config, ensure_ascii=False, allow_nan=False))
    request = dict(value["worker_request_kwargs"])
    existing = request.get("max_tokens")
    if existing is not None and existing != MAX_TOKENS:
        raise RuntimeError(
            f"Phase10 capped protocol requires max_tokens={MAX_TOKENS}, got {existing}"
        )
    request["max_tokens"] = MAX_TOKENS
    value["worker_request_kwargs"] = request
    return value


@contextmanager
def _v2_context() -> Iterator[None]:
    """Point the shared Phase10 implementation at the isolated v2 directory."""

    original = v1.EXPERIMENT_DIR
    v1.EXPERIMENT_DIR = EXPERIMENT_DIR
    try:
        yield
    finally:
        v1.EXPERIMENT_DIR = original


def _alias_status(target: Path, internal_stage: str, public_stage: str) -> None:
    status = load_json(target / "stage_status.json")
    details = status.get(internal_stage, {}).get("details")
    if status.get(internal_stage, {}).get("status") != "passed":
        raise RuntimeError(f"internal capped stage did not pass: {internal_stage}")
    v1._status(target, public_stage, details or {})


