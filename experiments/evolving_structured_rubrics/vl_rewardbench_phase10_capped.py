def _promote_native(source: Path, target: Path,
                    source_manifest: Mapping[str, Any],
                    target_manifest: Mapping[str, Any]) -> dict[str, int]:
    source_native = source / "run/native"
    target_native = target / "run/native"
    expected_identity = canonical_sha256(source_manifest["native"])
    if expected_identity != canonical_sha256(target_manifest["native"]):
        raise RuntimeError("native request identity changed in capped protocol")
    counts = {"cache_entries": 0, "replicate_artifacts": 0}
    for path in sorted((source_native / "cache").glob("*.json")):
        value = load_json(path)
        if (not isinstance(value, dict)
                or value.get("request_identity") != expected_identity
                or value.get("endpoint_id") not in v1.ENDPOINT_IDS):
            raise RuntimeError(f"unsafe native cache source: {path}")
        destination = target_native / "cache" / path.name
        if destination.exists() and load_json(destination) != value:
            raise RuntimeError(f"native promoted cache conflict: {destination}")
        atomic_write_json(destination, value)
        counts["cache_entries"] += 1
    for path in sorted(source_native.glob("replicate_*.json")):
        value = load_json(path)
        if (not isinstance(value, list)
                or any(item.get("request_identity") != expected_identity for item in value)):
            raise RuntimeError(f"unsafe native replicate source: {path}")
        destination = target_native / path.name
        if destination.exists() and load_json(destination) != value:
            raise RuntimeError(f"native promoted artifact conflict: {destination}")
        atomic_write_json(destination, value)
        counts["replicate_artifacts"] += 1
    return counts


def promote(config: Mapping[str, Any], output: Path) -> None:
    _require_public(STAGE_AUDIT)
    del output
    source = _source_target()
    target = _target()
    source_manifest_path = source / "frozen_manifest.json"
    target_manifest_path = target / "frozen_manifest.json"
    if not source_manifest_path.is_file() or not target_manifest_path.is_file():
        raise RuntimeError("source or target Phase10 manifest is missing")
    source_manifest = load_json(source_manifest_path)
    target_manifest = load_json(target_manifest_path)
    _validate_source_contract(source_manifest, target_manifest)
    old_spec = source_manifest["structured_worker_request_spec"]
    new_spec = target_manifest["structured_worker_request_spec"]
    reason_counts: dict[str, int] = {}
    unsafe_entries: list[dict[str, str]] = []
    promoted = 0
    already_present = 0
    scanned = 0
    for replicate_dir in sorted((source / "run/structured" / v1.FINAL_SYSTEM).glob(
            "replicate_*")):
        source_cache = replicate_dir / "cache/phase10_pairwise/pairwise"
        if not source_cache.is_dir():
            continue
        destination_root = (target / "run/structured" / v1.FINAL_SYSTEM
                            / replicate_dir.name / "cache/phase10_pairwise")
        destination = JsonPredictionCache(destination_root, CacheMode.READ_WRITE)
        for path in sorted(source_cache.glob("*.json")):
            scanned += 1
            value = load_json(path)
            output_value, metrics, reason = _safe_pairwise_entry(value, old_spec)
            if reason is not None:
                reason_counts[reason] = reason_counts.get(reason, 0) + 1
                unsafe_entries.append({
                    "replicate": replicate_dir.name,
                    "source_key_sha256": str(value.get("key_sha256", path.stem)),
                    "reason": reason,
                })
                continue
            key_payload = dict(value["key_payload"])
            key_payload["request_spec"] = new_spec
            existing = destination.get_pairwise(key_payload)
            if existing is not None:
                if existing.output != output_value or existing.generation_metrics != metrics:
                    raise RuntimeError("promoted pairwise cache conflicts with existing v2 entry")
                already_present += 1
                continue
            destination.put_pairwise(key_payload, output_value, metrics)
            promoted += 1
    native_counts = _promote_native(source, target, source_manifest, target_manifest)
    report = {
        "schema_version": "1.0.0",
        "protocol": "non_binding_max_tokens_cache_promotion_v1",
        "source_experiment": SOURCE_EXPERIMENT_DIR,
        "target_experiment": EXPERIMENT_DIR,
        "max_tokens": MAX_TOKENS,
        "source_manifest_sha256": canonical_sha256(source_manifest),
        "target_manifest_sha256": canonical_sha256(target_manifest),
        "structured_scanned": scanned,
        "structured_promoted": promoted,
        "structured_already_present": already_present,
        "structured_unsafe": len(unsafe_entries),
        "unsafe_reason_counts": reason_counts,
        "native_promoted": native_counts,
        "accuracy_semantics": "promoted outputs ended before the cap on one clean attempt",
    }
    atomic_write_json(target / "cache_promotion_report.json", report)
    atomic_write_json(target / "cache_promotion_unsafe.json", {
        "schema_version": "1.0.0", "items": unsafe_entries,
    })
    v1._status(target, STAGE_PROMOTE, report)
    print(json.dumps(report, indent=2, ensure_ascii=False))


