def _extract_json_object(raw: str) -> str | None:
    """Return the outer JSON object without attempting semantic recovery."""

    start = raw.find("{")
    end = raw.rfind("}")
    return None if start < 0 or end < start else raw[start:end + 1]


def _escape_invalid_json_backslashes(value: str) -> str:
    """Escape only backslashes that cannot begin a legal JSON escape.

    This deliberately does not repair quotes, commas, truncation, braces, or
    schema errors.  It therefore recovers LaTeX such as ``\\pi`` while leaving
    every valid JSON escape byte-for-byte unchanged.
    """

    result: list[str] = []
    for index, character in enumerate(value):
        if (character == "\\" and
                (index + 1 == len(value) or value[index + 1] not in _VALID_JSON_ESCAPES)):
            result.append("\\\\")
        else:
            result.append(character)
    return "".join(result)


def _safe_latex_json_repair(raw: object) -> tuple[str, PairwiseVoteOutput] | None:
    """Conservatively recover a complete pairwise JSON object with bad LaTeX escapes."""

    if not isinstance(raw, str):
        return None
    outer = _extract_json_object(raw)
    if outer is None:
        return None
    repaired = _escape_invalid_json_backslashes(outer)
    if repaired == outer:
        return None
    try:
        value = json.loads(repaired, strict=False)
    except json.JSONDecodeError:
        return None
    if (not isinstance(value, dict) or set(value) != _PAIRWISE_FIELDS
            or any(not isinstance(item, str) for item in value.values())
            or value["answer"] not in {"A", "B", "None"}):
        return None
    normalized = json.dumps(value, ensure_ascii=False, allow_nan=False)
    try:
        parsed = parse_pairwise_vote_response(normalized)
    except Exception:
        return None
    return normalized, PairwiseVoteOutput(
        parsed.vote, True, normalized, None, 1, parsed.thought, parsed.answer_valid)


def _pairwise_json_schema() -> dict[str, Any]:
    string_fields = {name: {"type": "string"} for name in _PAIRWISE_FIELDS}
    string_fields["answer"] = {"type": "string", "enum": ["A", "B", "None"]}
    return {
        "type": "json_schema",
        "json_schema": {
            "name": "critiq_pairwise_format_repair",
            "strict": True,
            "schema": {
                "type": "object",
                "additionalProperties": False,
                "required": ["analysis_a", "analysis_b", "thought", "answer"],
                "properties": string_fields,
            },
        },
    }


