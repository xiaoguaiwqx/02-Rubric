def failure_rescue_run(config: Mapping[str, Any], output: Path) -> None:
    """Make one separately audited fourth attempt for the sole residual failure."""

    _require_public(STAGE_FAILURE_RETRY_REPORT)
    target, source_manifest, records, order_schedule, _, final = _load_v2_frozen(
        config, output)
    retry_work = target / FAILURE_RETRY_DIR
    retry_overlay_value = load_json(retry_work / "retry_overlay.json")
    failed = [item for item in retry_overlay_value["items"] if not item["success"]]
    if len(failed) != 1:
        raise RuntimeError(f"final rescue requires exactly one residual failure, got {len(failed)}")
    item = failed[0]
    frozen = {
        "schema_version": FORMAT_REPAIR_SCHEMA_VERSION,
        "protocol": "phase10_single_residual_original_pairwise_rescue_v1",
        "source_manifest_sha256": canonical_sha256(source_manifest),
        "failure_retry_overlay_sha256": v1.file_sha256(
            retry_work / "retry_overlay.json"),
        "additional_attempt_number": MAX_ADDITIONAL_ATTEMPTS + 1,
        "request_semantics": {
            "prompt": "original_pairwise_worker_prompt",
            "temperature": 0.5,
            "max_tokens": MAX_TOKENS,
            "response_format": None,
            "endpoint_id": item["endpoint_id"],
        },
        "selection_uses_gold": False,
        "item": {key: item[key] for key in (
            "key", "replicate", "sample_index", "sample_id", "criterion_name",
            "endpoint_id", "source_output_sha256")},
    }
    atomic_write_json(retry_work / "final_rescue_frozen.json", frozen)
