    initial = v1.build_multicrit_open_ended_init_rubric()
    original = load_json(target / "run/combined/logical_votes.json")
    votes = {name: [] for name in (
        v1.INITIAL_SYSTEM, v1.EQUAL_SYSTEM, v1.WEIGHTED_SYSTEM, v1.VISUAL_SYSTEM)}
