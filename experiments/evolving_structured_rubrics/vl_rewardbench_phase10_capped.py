def failure_retry_freeze(config: Mapping[str, Any], output: Path) -> None:
    """Freeze the failures not handled by the 24-item format repair."""

    _require_public(STAGE_FORMAT_REPAIR_REPORT)
    target, source_manifest, _, _, _, _ = _load_v2_frozen(config, output)
    format_work = target / FORMAT_REPAIR_DIR
    format_manifest = load_json(format_work / "frozen_manifest.json")
    _validate_format_repair_source(target, format_manifest)
    excluded = {str(item["key"]) for item in format_manifest["items"]}
    items: list[dict[str, Any]] = []
    for replicate in range(v1.legacy.K):
        path = _prediction_path(target, replicate)
        prediction = PairwisePredictionOutput.load_json(path)
        assignments = load_json(path.parents[1] / "endpoint_assignments.json")["assignments"]
        for sample_index, (sample_id, row) in enumerate(zip(
                prediction.sample_ids, prediction.node_outputs)):
            for criterion_name, source_output in row.items():
                if source_output.parse_ok:
                    continue
                key = _source_output_key(replicate, sample_index, criterion_name)
                if key in excluded:
                    continue
                items.append({
                    "key": key,
                    "replicate": replicate + 1,
                    "sample_index": sample_index,
                    "sample_id": sample_id,
                    "criterion_name": criterion_name,
                    "endpoint_id": assignments[f"{sample_id}::{criterion_name}"],
                    "source_output_sha256": canonical_sha256(source_output.to_dict()),
                    "source_parse_error": source_output.parse_error,
                })
    if len(items) != EXPECTED_REMAINING_FAILURES:
        raise RuntimeError(
            f"unexpected remaining Phase10 failure population: {len(items)}")
    frozen = {
        "schema_version": FORMAT_REPAIR_SCHEMA_VERSION,
        "protocol": "phase10_original_pairwise_retry_v1",
        "source_experiment": EXPERIMENT_DIR,
        "source_manifest_sha256": canonical_sha256(source_manifest),
        "source_prediction_sha256": format_manifest["source_prediction_sha256"],
        "format_repair_manifest_sha256": canonical_sha256(format_manifest),
        "format_repair_overlay_sha256": v1.file_sha256(
            format_work / "repair_overlay.json"),
        "target_count": len(items),
        "max_additional_attempts": MAX_ADDITIONAL_ATTEMPTS,
        "request_semantics": {
            "prompt": "original_pairwise_worker_prompt",
            "temperature": 0.5,
            "max_tokens": MAX_TOKENS,
            "response_format": None,
            "endpoint_assignment": "original_frozen_endpoint",
        },
        "selection_uses_gold": False,
        "items": items,
    }
    work = target / FAILURE_RETRY_DIR
    atomic_write_json(work / "frozen_manifest.json", frozen)
    v1._status(target, STAGE_FAILURE_RETRY_FREEZE, {
        "target_count": len(items),
        "max_additional_attempts": MAX_ADDITIONAL_ATTEMPTS,
    })
    print(json.dumps({
        "target_count": len(items),
        "max_additional_attempts": MAX_ADDITIONAL_ATTEMPTS,
        "maximum_new_requests": len(items) * MAX_ADDITIONAL_ATTEMPTS,
    }, indent=2, ensure_ascii=False))


def _original_retry_evaluator(
    config: Mapping[str, Any],
    rows: Sequence[Mapping[str, Any]],
    router: Any,
    source_manifest: Mapping[str, Any],
) -> PairwiseVoteMultiModalEvaluator:
    capped = _capped_config(config)
    request = dict(capped["worker_request_kwargs"])
    request["temperature"] = 0.5
    evaluator = PairwiseVoteMultiModalEvaluator(
        worker_args={
            "model": capped["model"],
            "api_keys": "EMPTY",
            "request_kwargs": request,
            "api_retry_attempts": capped["api_retry_attempts"],
        },
        dataset=rows,
        backend_id=source_manifest["structured_worker_request_spec"]["backend_id"],
        max_concurrent=router.spec.global_request_concurrency,
        max_retries=0,
        max_data_chars=None,
        encode_local_image=True,
        call_backend=router,
    )
    if evaluator.request_spec().to_dict() != source_manifest["structured_worker_request_spec"]:
        raise RuntimeError("failure retry no longer uses the original Pairwise request identity")
    return evaluator


