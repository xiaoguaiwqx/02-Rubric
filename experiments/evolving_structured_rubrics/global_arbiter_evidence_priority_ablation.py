def _smoke_records(
    records: Sequence[Mapping[str, Any]], seed: int,
) -> tuple[Mapping[str, Any], ...]:
    quotas = {"general": 7, "hallucination": 30, "reasoning": 13}
    selected_ids: set[str] = set()
    for group, quota in quotas.items():
        grouped: dict[str, list[Mapping[str, Any]]] = defaultdict(list)
        for record in records:
            if str(record.get("group")) == group:
                identity = str(record.get("benchmark_id", record["sample_id"]))
                grouped[vlrb._official_dataset(identity)].append(record)
        if not grouped or quota < len(grouped):
            raise RuntimeError(f"cannot stratify smoke group {group}")
        counts = {key: len(value) for key, value in grouped.items()}
        allocation = {key: 1 for key in grouped}
        remaining = quota - len(grouped)
        if remaining:
            weights = {key: max(0, count - 1) for key, count in counts.items()}
            total = sum(weights.values())
            raw = {key: remaining * weights[key] / total for key in grouped}
            floors = {key: int(math.floor(value)) for key, value in raw.items()}
            for key, value in floors.items():
                allocation[key] += value
            leftover = remaining - sum(floors.values())
            ranked = sorted(
                grouped, key=lambda key: (-(raw[key] - floors[key]), key))
            for key in ranked[:leftover]:
                allocation[key] += 1
        for source, items in grouped.items():
            ordered = sorted(items, key=lambda item: hashlib.sha256(
                f"arbiter-ablation|{seed}|{group}|{source}|{item['sample_id']}"
                .encode("utf-8")).hexdigest())
            selected_ids.update(str(item["sample_id"])
                                for item in ordered[:allocation[source]])
    selected = tuple(record for record in records
                     if str(record["sample_id"]) in selected_ids)
    if len(selected) != 50:
        raise RuntimeError(f"smoke selector produced {len(selected)} rows")
    return selected


def freeze(config: Mapping[str, Any], output: Path) -> None:
    target = _target(output)
    manifest = _manifest(config, output, include_endpoints=True)
    if manifest["endpoint_identities"] != manifest["v2_endpoint_identities"]:
        raise RuntimeError("live endpoints do not match the frozen formal V2")
    records = support.records(output)
    rubric = support.rubric(output)
    _, bundles = support.source_index(output, records, rubric)
    expected_reports = len(records) * K * len(rubric.root_ids)
    if (bundles.get("source_root_report_count") != expected_reports
            or bundles.get("full_field_report_count") != expected_reports):
        raise RuntimeError("18,705 frozen subtree reports are not complete")
    smoke = _smoke_records(records, _settings(config)["subset_seed"])
    path = target / "frozen_manifest.json"
    if path.is_file() and load_json(path) != manifest:
        raise RuntimeError("Arbiter ablation frozen manifest drift")
    atomic_write_json(path, manifest)
    atomic_write_json(target / "arbiter_bundle_manifest.json", bundles)
    atomic_write_json(target / "subsets" / "smoke_50.json", {
        "schema_version": SCHEMA_VERSION,
        "sample_count": len(smoke),
        "sample_ids": [str(item["sample_id"]) for item in smoke],
        "group_counts": dict(Counter(str(item["group"]) for item in smoke)),
        "source_counts": dict(Counter(
            vlrb._official_dataset(str(item["benchmark_id"])) for item in smoke)),
        "selection_uses_model_outputs": False,
    })
    atomic_write_json(target / "prompt_specs" / "neutral.json", {
        "schema_version": SCHEMA_VERSION,
        "protocol_version": PROTOCOL_VERSION,
        "system_prompt": NEUTRAL_SYSTEM_PROMPT,
        "parser": "answer_A_or_B_or_None",
        "variants": list(VARIANTS),
    })
    atomic_write_json(target / "prompt_specs" / "factuality_first_reference.json", {
        "schema_version": SCHEMA_VERSION,
        "source_experiment": V2_EXPERIMENT,
        "system_prompt": formal.GLOBAL_ARBITER_AB_ONLY_SYSTEM_PROMPT,
        "system_prompt_sha256": V2_SYSTEM_SHA256,
        "regenerated": False,
    })
    atomic_write_json(target / "v2_reuse_manifest.json", {
        "schema_version": SCHEMA_VERSION,
        "source_experiment": V2_EXPERIMENT,
        "source_artifact_sha256": {
            key: value for key, value in manifest["source_artifact_sha256"].items()
            if key.startswith("v2_")
        },
        "new_model_requests": 0,
    })
    details = {
        "sample_count": len(records),
        "smoke_sample_count": len(smoke),
        "source_root_report_count": expected_reports,
        "new_full_arbiter_request_count": len(records) * K * len(VARIANTS),
        "reused_v2_request_count": len(records) * K,
    }
    support.status(target, STAGES[0], details)
    print(json.dumps(details, indent=2))


def _load_frozen(config: Mapping[str, Any], output: Path):
    target = _target(output)
    support.require(target, STAGES[0])
    manifest = load_json(target / "frozen_manifest.json")
    expected = _manifest(config, output, include_endpoints=False)
    for key, value in expected.items():
        if manifest.get(key) != value:
            raise RuntimeError(f"Arbiter ablation frozen manifest drift: {key}")
    records = support.records(output)
    rubric = support.rubric(output)
    source_by_id = {
        str(sample["sample_id"]): sample
        for sample in support.source_prediction(output)["samples"]
    }
    return target, manifest, records, rubric, source_by_id


def _verify_live(config: Mapping[str, Any], manifest: Mapping[str, Any]) -> None:
    actual = base._inspect_endpoints(
        config, BackendPoolSpec.from_dict(config["backend_pool"]))
    if actual != manifest.get("endpoint_identities"):
        raise RuntimeError("Arbiter ablation endpoint identity drift")


def _v2_votes(
    output: Path, records: Sequence[Mapping[str, Any]],
) -> list[list[int | None]]:
    prediction = load_json(
        _v2_target(output) / "predictions" / "arbiter_ab_only_full.json")
    if [str(item.get("sample_id")) for item in prediction.get("samples", ())] != [
            str(item["sample_id"]) for item in records]:
        raise RuntimeError("formal V2 sample order drift")
    votes = formal._s5_vote_matrices(prediction)
    report = load_json(_v2_target(output) / "final_report.json")
    frozen = report.get("systems", {}).get(V2_SYSTEM, {}).get(
        "votes_by_replicate")
    if frozen != votes:
        raise RuntimeError("formal V2 prediction/report vote drift")
    recomputed = vlrb_metrics._system_metrics(records, votes)
    frozen_metrics = report["systems"][V2_SYSTEM]["metrics"]
    for key in ("strict_accuracy", "overall_acc", "macro_acc", "coverage",
                "correct_count", "original_index_predictions"):
        if recomputed[key] != frozen_metrics[key]:
            raise RuntimeError(f"formal V2 metric drift: {key}")
    return votes


def audit(config: Mapping[str, Any], output: Path) -> None:
    target, manifest, records, rubric, source_by_id = _load_frozen(config, output)
    source = source_by_id[str(records[0]["sample_id"])]
    row = support.vlrb_rows((records[0],))[0]
    displayed = support.ordered_row(row, int(source["orders"][0]), 0)
    reports, _, _ = support.source_report_bundle(output, source, 0, rubric)
    v0_prompt = _label_only_user_prompt(displayed, reports)
    v1_prompt = _full_report_user_prompt(displayed, reports)
    _, v2_checks = _v2_identity(output)
    _v2_votes(output, records)
    bundle_manifest = load_json(target / "arbiter_bundle_manifest.json")
    neutral_difference = (
        formal.GLOBAL_ARBITER_AB_ONLY_SYSTEM_PROMPT.replace(
            FACTUALITY_FIRST_PARAGRAPH, "") == NEUTRAL_SYSTEM_PROMPT)
    checks = {
        "record_count_1247": len(records) == VLRB_COUNT,
        "five_roots": len(rubric.root_ids) == 5,
        "source_reports_18705": bundle_manifest["source_root_report_count"]
            == len(records) * K * len(rubric.root_ids) == 18705,
        "source_reports_have_full_fields": bundle_manifest[
            "full_field_report_count"] == 18705,
        "neutral_is_single_paragraph_deletion": neutral_difference,
        "neutral_has_no_factuality_first": FACTUALITY_FIRST_PARAGRAPH.strip()
            not in NEUTRAL_SYSTEM_PROMPT,
        "same_neutral_system_for_v0_v1": True,
        "v0_contains_only_labels": all(
            key not in v0_prompt for key in ('"analysis_a"', '"analysis_b"',
                                             '"thought"')),
        "v1_contains_full_reports": all(
            key in v1_prompt for key in ('"analysis_a"', '"analysis_b"',
                                         '"thought"')),
        "same_pair_prefix": v0_prompt.split("## Subtree Assessments")[0]
            == v1_prompt.split("## Subtree Assessments")[0],
        "same_root_names": all(
            report["criterion_name"] in v0_prompt
            and report["criterion_name"] in v1_prompt for report in reports),
        "parser_accepts_none": formal.parse_global_arbiter_ab_only_response(
            '{"answer":"None"}') == {"answer": "None"},
        "v2_exact_reuse": all(v2_checks.values()),
        "v2_new_model_requests_zero": load_json(
            target / "v2_reuse_manifest.json")["new_model_requests"] == 0,
        "schedule_identical": manifest["schedule_sha256"] == V2_SCHEDULE_SHA256,
        "gold_is_dataset_field": all(
            int(record["preferred_original_index"]) in (0, 1)
            for record in records),
    }
    if not all(checks.values()):
        raise RuntimeError(f"Arbiter ablation audit failed: {checks}")
    atomic_write_json(target / "offline_audit.json", {
        "schema_version": SCHEMA_VERSION, "offline_only": True,
        "checks": checks,
    })
    support.status(target, STAGES[1], checks)
    print(json.dumps(checks, indent=2))


