def _v2_identity(output: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    target = _v2_target(output)
    required = (
        "frozen_manifest.json", "prompt_spec.json", "final_report.json",
        "predictions/arbiter_ab_only_full.json",
    )
    missing = [name for name in required if not (target / name).is_file()]
    if missing:
        raise RuntimeError(f"formal V2 artifacts are missing: {missing}")
    manifest = load_json(target / "frozen_manifest.json")
    prompt = load_json(target / "prompt_spec.json")
    checks = {
        "protocol": manifest.get("protocol_version") == V2_PROTOCOL,
        "prompt_version": manifest.get("prompt_version") == V2_PROMPT_VERSION,
        "rubric": manifest.get("rubric_sha256") == V2_RUBRIC_SHA256,
        "schedule": manifest.get("schedule_sha256") == V2_SCHEDULE_SHA256,
        "system_hash": manifest.get("system_prompt_sha256") == V2_SYSTEM_SHA256,
        "system_text": prompt.get("system_prompt")
            == formal.GLOBAL_ARBITER_AB_ONLY_SYSTEM_PROMPT,
        "model": all(item.get("model") == "Qwen/Qwen3-VL-8B-Instruct"
                     for item in manifest.get("endpoint_identities", ())),
        "k": manifest.get("settings", {}).get("k") == K,
        "temperature": manifest.get("settings", {}).get("temperature") == 0.5,
        "max_tokens": manifest.get("settings", {}).get("max_tokens") == 2048,
        "generation_seed": manifest.get("settings", {}).get(
            "generation_seed_policy") == "unset",
        "semantic_answers": manifest.get("settings", {}).get(
            "semantic_answer_space") == ["A", "B", "None"],
    }
    if not all(checks.values()):
        raise RuntimeError(f"formal V2 identity drift: {checks}")
    return manifest, checks


